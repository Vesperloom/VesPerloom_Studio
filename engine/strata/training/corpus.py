def sample(rng, n):
    family = rng.integers(0, 4, n)
    factors = rng.normal(size=(n, 4)).astype("f")
    factors[:, 0] = 0.45 * factors[:, 0] + rng.choice([-0.95, 0.95], n)
    code = MEANS[family] + factors @ FACTORS + 0.20 * rng.normal(size=(n, len(FEATURES)))
    return code.astype("f"), np.eye(4, dtype="f")[family]
